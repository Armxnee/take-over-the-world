"""Pack the user's pixel sprites (pixel_art_sprites_16x16.zip -> data/sprites2/*.png) into
src/client/SpriteData.luau.

The PNGs are 1024x1024 renders of 64x64 pixel art on a grid background (no alpha):
  1. sample the centre of each 16px block (median) -> 64x64
  2. flood-fill the background from the borders (colours close to the border palette)
  3. crop to the sprite and pad to a square
  4. split into layers:
       base - colours drawn as-is (accents, canopies, outlines, cargo)
       tint - grey shade of the "paint" (grey / olive hull) multiplied at runtime by the
              owner's nation colour (Standard) or a skin colour (Arctic, Desert, ...)
       edge - 1px ring outside the silhouette (nation colour on skinned units)
Run from the project root: py -I tools/build_sprites.py
"""
import colorsys, os, statistics
from collections import deque
from PIL import Image

SRC = "data/sprites2"
OUT = "src/client/SpriteData.luau"
FILES = {
    "TroopTransport": "troop_transport_boat_16x16.png",
    "Cargo": "cargo_boat_16x16.png",
    "Warship": "warship_16x16.png",
    "Fighter": "fighter_plane_16x16.png",
    "Bomber": "tactical_bomber_plane_16x16.png",
    "Missile": "missile_16x16.png",
    "Nuke": "nuke_16x16.png",
}
N = 64


def down(path):
    im = Image.open(path).convert("RGB")
    s = im.width // N
    px = [[None] * N for _ in range(N)]
    for by in range(N):
        for bx in range(N):
            sm = [im.getpixel((bx * s + s // 2 + dx, by * s + s // 2 + dy)) for dx in (-3, 0, 3) for dy in (-3, 0, 3)]
            px[by][bx] = tuple(int(statistics.median(c[i] for c in sm)) for i in range(3))
    return px


def dist(a, b):
    return sum((a[i] - b[i]) ** 2 for i in range(3)) ** 0.5


def is_paint(c):
    r, g, b = (v / 255 for v in c)
    h, s, v = colorsys.rgb_to_hsv(r, g, b)
    if v < 0.2:
        return False  # outlines stay dark
    if s < 0.22:
        return True  # greys / whites (hull, missile body)
    hue = h * 360
    return 55 <= hue <= 115 and s < 0.62  # olive / camo greens


out = ["--!strict", "-- Generated by tools/build_sprites.py from the user's pixel sprite pack. Do not edit.", "return {"]
for name, f in FILES.items():
    px = down(os.path.join(SRC, f))
    border = [px[y][x] for y in range(N) for x in range(N) if x in (0, N - 1) or y in (0, N - 1)]
    pal = []
    for c in border:
        if all(dist(c, p) > 6 for p in pal):
            pal.append(c)
    bg = [[False] * N for _ in range(N)]
    q = deque((x, y) for y in range(N) for x in range(N) if x in (0, N - 1) or y in (0, N - 1))
    for x, y in q:
        bg[y][x] = True
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < N and 0 <= ny < N and not bg[ny][nx] and min(dist(px[ny][nx], p) for p in pal) < 20:
                bg[ny][nx] = True
                q.append((nx, ny))
    xs = [x for y in range(N) for x in range(N) if not bg[y][x]]
    ys = [y for y in range(N) for x in range(N) if not bg[y][x]]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    S = max(x1 - x0, y1 - y0) + 3  # +1px each side for the outline ring
    ox = x0 - (S - (x1 - x0 + 1)) // 2
    oy = y0 - (S - (y1 - y0 + 1)) // 2
    solid = [[False] * S for _ in range(S)]
    base, tint, edge = [], [], []
    for y in range(S):
        for x in range(S):
            sx, sy = ox + x, oy + y
            if 0 <= sx < N and 0 <= sy < N and not bg[sy][sx]:
                solid[y][x] = True
    # compact encoding (Studio caps script source at 200k chars): one char per pixel
    #   base: palette index (ALPHA) or "." ; tint: grey level / 4 (ALPHA) or "." ; edge: 0/1
    ALPHA = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ-_"
    from collections import Counter
    q = lambda c: tuple(min(255, (v // 8) * 8 + 4) for v in c)
    counts = Counter(q(px[oy + y][ox + x]) for y in range(S) for x in range(S)
                     if solid[y][x] and not is_paint(px[oy + y][ox + x]))
    pal = [c for c, _ in counts.most_common(64)]
    def pidx(c):
        c = q(c)
        if c in pal:
            return pal.index(c)
        return min(range(len(pal)), key=lambda i: dist(pal[i], c))
    for y in range(S):
        for x in range(S):
            sx, sy = ox + x, oy + y
            if solid[y][x]:
                c = px[sy][sx]
                if is_paint(c):
                    v = min(255, int(max(c) * 1.12))
                    base.append(".")
                    tint.append(ALPHA[min(63, v // 4)])
                else:
                    base.append(ALPHA[pidx(c)])
                    tint.append(".")
                edge.append("0")
            else:
                base.append(".")
                tint.append(".")
                ring = any(0 <= x + dx < S and 0 <= y + dy < S and solid[y + dy][x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                edge.append("1" if ring else "0")
    pal_s = ", ".join('"%02x%02x%02x"' % c for c in pal)
    out.append(f'\t{name} = {{ size = {S}, pal = {{ {pal_s} }}, base = "{"".join(base)}", tint = "{"".join(tint)}", edge = "{"".join(edge)}" }},')
    print(name, S, "x", S)
out.append("}")
open(OUT, "w").write("\n".join(out) + "\n")
print("bytes", os.path.getsize(OUT))
