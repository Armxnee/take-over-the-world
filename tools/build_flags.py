"""Pixel versions of the real flags of every region in our maps (countries, plus US
states on the North America map), from flagcdn.com PNGs (public-domain flag artwork).

Each flag is cut down to 30x20 pixels: the full-size flag is reduced to its few real
colours (median cut), then box-sampled and snapped to that palette so stripes stay crisp.
Output:
  src/shared/FlagData/Names.luau   region name -> flag code
  src/shared/FlagData/PixA.luau    code -> "rrggbb.. | 600 palette indices"  (codes a-l)
  src/shared/FlagData/PixB.luau    (codes m-z)
Run from the project root: py -I tools/build_flags.py
"""
import io, json, os, re, unicodedata, urllib.request
from concurrent.futures import ThreadPoolExecutor
import numpy as np
import shapefile
from PIL import Image

FW, FH = 30, 20
OTHER = r"C:/Users/izzyn/Downloads/CountyBall War game/data/raw/"
ADM0 = "data/raw/ne_50m_admin_0_countries/ne_50m_admin_0_countries"
ADM1 = OTHER + "ne_10m_admin_1_states_provinces/ne_10m_admin_1_states_provinces"
CACHE = "data/raw/flags"
IDX = "0123456789abcdefghijklmnopqrstuvwxyz"


def ascii_name(s):
    s = unicodedata.normalize("NFKD", s or "").encode("ascii", "ignore").decode()
    return s.replace('"', "").replace("\\", "").strip()


codes = json.load(open("data/raw/flag_codes.json", encoding="utf-8"))
lookup = {}
for r in shapefile.Reader(ADM0).iterRecords():
    c = (r["ISO_A2_EH"] or "").lower()
    if c in codes:
        lookup[ascii_name(r["NAME"])] = c
for r in shapefile.Reader(ADM1).iterRecords():
    if r["adm0_a3"] not in ("USA", "CAN", "MEX", "KOR", "PRK"):
        continue
    nm = ascii_name(r["name_en"] or r["name"])
    iso = (r["iso_3166_2"] or "").lower()
    c = iso if iso in codes else (r["iso_a2"] or "").lower()
    if c in codes:
        lookup.setdefault(nm, c)
for c, nm in codes.items():
    lookup.setdefault(ascii_name(nm), c)

names = {}
for f in os.listdir("src/shared/Maps"):
    if f.endswith("Look.luau"):
        continue
    src = open(os.path.join("src/shared/Maps", f), encoding="utf-8").read()
    m = re.search(r"names = \{ (.*?) \},", src)
    for nm in re.findall(r'"([^"]*)"', m.group(1)):
        if nm in lookup:
            names[nm] = lookup[nm]
        elif nm != "?":
            print("  no flag:", nm)
need = sorted(set(names.values()))
print(len(names), "regions ->", len(need), "flags")

os.makedirs(CACHE, exist_ok=True)


def fetch(c):
    p = os.path.join(CACHE, c + ".png")
    if not os.path.exists(p):
        req = urllib.request.Request(f"https://flagcdn.com/w320/{c}.png", headers={"User-Agent": "Mozilla/5.0"})
        open(p, "wb").write(urllib.request.urlopen(req, timeout=30).read())
    return c


with ThreadPoolExecutor(8) as ex:
    list(ex.map(fetch, need))


def pixel(c):
    im = Image.open(os.path.join(CACHE, c + ".png")).convert("RGB")
    q = im.quantize(colors=12, method=Image.Quantize.MEDIANCUT)
    pal = np.array(q.getpalette()[:36], np.float32).reshape(-1, 3)
    # keep colours that cover a real share of the flag
    hist = np.bincount(np.asarray(q).flatten(), minlength=12)
    keep = [i for i in range(len(pal)) if hist[i] > 0.004 * hist.sum()]
    pal = pal[keep]
    small = np.asarray(im.resize((FW, FH), Image.BOX), np.float32).reshape(-1, 3)
    idx = ((small[:, None, :] - pal[None]) ** 2).sum(-1).argmin(1)
    used = sorted(set(idx.tolist()))
    remap = {u: k for k, u in enumerate(used)}
    hexes = "".join("%02x%02x%02x" % tuple(int(v) for v in pal[u]) for u in used)
    return hexes + "|" + "".join(IDX[remap[i]] for i in idx)


data = {c: pixel(c) for c in need}
os.makedirs("src/shared/FlagData", exist_ok=True)
HEAD = "--!strict\n-- Generated by tools/build_flags.py (flag artwork: flagcdn.com, public domain). Do not edit.\n"
with open("src/shared/FlagData/Names.luau", "w", encoding="utf-8") as fh:
    fh.write(HEAD + "return {\n" + "".join(f'\t["{n}"] = "{c}",\n' for n, c in sorted(names.items())) + "}\n")
for part, test in (("PixA", lambda c: c < "m"), ("PixB", lambda c: c >= "m")):
    with open(f"src/shared/FlagData/{part}.luau", "w", encoding="utf-8") as fh:
        fh.write(HEAD + "return {\n" + "".join(f'\t["{c}"] = "{d}",\n' for c, d in data.items() if test(c)) + "}\n")
    print(part, os.path.getsize(f"src/shared/FlagData/{part}.luau"))
# contact sheet for review
sheet = Image.new("RGB", (16 * (FW + 2), (len(need) // 16 + 1) * (FH + 2)), (40, 40, 40))
for k, c in enumerate(need):
    hx, ix = data[c].split("|")
    pal = [tuple(int(hx[i:i + 2], 16) for i in (j, j + 2, j + 4)) for j in range(0, len(hx), 6)]
    im = Image.new("RGB", (FW, FH))
    im.putdata([pal[IDX.index(ch)] for ch in ix])
    sheet.paste(im, ((k % 16) * (FW + 2), (k // 16) * (FH + 2)))
sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save("data/flags_preview.png")
