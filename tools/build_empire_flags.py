"""Pixel flags of the historical empires a country can found (Take Over the World!, 2026-11-07).

Each empire's flag comes from Wikimedia Commons (historical flags: public domain), rendered to PNG by
Commons (Special:FilePath ... ?width=320), then cut down to 30 x 20 pixels like the country flags
(tools/build_flags.py: median-cut palette of the real colours, box-sampled, snapped to the palette).
Output: src/shared/Data/FlagData/Empires.luau  ("emp_<key>" -> "rrggbb.. | 600 palette indices")
        tools/assets_out/empire_flags_preview.png
Run from the project root: py -I tools/build_empire_flags.py
"""
import io
import os
import time
import urllib.parse
import urllib.request

import numpy as np
from PIL import Image

FW, FH = 30, 20
IDX = "0123456789abcdefghijklmnopqrstuvwxyz"
CACHE = os.path.join("tools", "assets_out", "empire_flags")
UA = {"User-Agent": "TakeOverTheWorld-flagbuilder/1.0 (Roblox game; contact via github.com/Armxnee)"}

# key: candidate Commons file names (first that downloads wins)
EMPIRES = {
    "british": ["Flag_of_the_United_Kingdom.svg"],
    "german": ["Flag_of_the_German_Empire.svg"],
    "russian": ["Flag_of_the_Russian_Empire_(black-yellow-white).svg", "Flag_of_Russia_(1858–1883).svg"],
    "ottoman": ["Flag_of_the_Ottoman_Empire_(1844–1922).svg", "Flag_of_the_Ottoman_Empire.svg"],
    "japanese": ["Imperial_Standard_of_Japan.svg", "Flag_of_Japan_(1870–1999).svg"],
    "french": ["Imperial_Standard_of_Napoléon_I.svg", "Flag_of_France.svg"],
    "austrian": ["Flag_of_the_Habsburg_Monarchy.svg", "Flag_of_Austria-Hungary_(1869-1918).svg"],
    "spanish": ["Flag_of_Cross_of_Burgundy.svg", "Cross_of_Burgundy_flag.svg"],
    "portuguese": ["Flag_of_Portugal_(1830).svg"],
    "qing": ["Flag_of_the_Qing_dynasty_(1889–1912).svg", "Flag_of_China_(1889–1912).svg"],
    "persian": ["State_flag_of_Persia_(1907–1933).svg"],
    "brazilian": ["Flag_of_the_Empire_of_Brazil_(1870–1889).svg", "Flag_of_Empire_of_Brazil_(1870-1889).svg"],
    "mexican": ["Flag_of_the_Second_Mexican_Empire.svg"],
    "ethiopian": ["Flag_of_Ethiopia_(1897–1936;_1941–1974).svg", "Flag_of_the_Ethiopian_Empire.svg"],
    "byzantine": ["Byzantine_imperial_flag,_14th_century.svg", "Byzantine_imperial_flag,_14th_century,_square.svg"],
    "roman": ["Vexilloid_of_the_Roman_Empire.svg"],
    "korean": ["Flag_of_Korea_(1882–1910).svg"],
    "swedish": ["Naval_Ensign_of_Sweden.svg"],
    "dutch": ["Prinsenvlag.svg", "Flag_of_the_Prince_of_Orange.svg"],
}


def fetch(key):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, key + ".png")
    if os.path.exists(path):
        return path, "cached"
    for name in EMPIRES[key]:
        url = "https://commons.wikimedia.org/wiki/Special:FilePath/" + urllib.parse.quote(name) + "?width=320"
        try:
            req = urllib.request.Request(url, headers=UA)
            data = urllib.request.urlopen(req, timeout=30).read()
            Image.open(io.BytesIO(data)).verify()
            open(path, "wb").write(data)
            return path, name
        except Exception as e:  # noqa: BLE001 - try the next name
            print("   ", key, name, "->", e)
            time.sleep(0.5)
    return None, None


def pixel(path):
    im = Image.open(path).convert("RGBA")
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
    im = Image.alpha_composite(bg, im).convert("RGB")
    # fill the 3:2 frame (a square flag is centred on its own edge colour)
    w, h = im.size
    if abs(w / h - 1.5) > 0.05:
        target_w = max(w, int(h * 1.5))
        target_h = max(h, int(w / 1.5))
        edge = im.getpixel((0, h // 2))
        canvas = Image.new("RGB", (target_w, target_h), edge)
        canvas.paste(im, ((target_w - w) // 2, (target_h - h) // 2))
        im = canvas
    q = im.quantize(colors=12, method=Image.Quantize.MEDIANCUT)
    pal = np.array(q.getpalette()[:36], np.float32).reshape(-1, 3)
    hist = np.bincount(np.asarray(q).flatten(), minlength=12)
    keep = [i for i in range(len(pal)) if hist[i] > 0.01 * hist.sum()]
    pal = pal[keep]
    small = np.asarray(im.resize((FW, FH), Image.BOX), np.float32).reshape(-1, 3)
    idx = ((small[:, None, :] - pal[None]) ** 2).sum(-1).argmin(1)
    used = sorted(set(idx.tolist()))
    remap = {u: k for k, u in enumerate(used)}
    hexes = "".join("%02x%02x%02x" % tuple(int(v) for v in pal[u]) for u in used)
    return hexes + "|" + "".join(IDX[remap[i]] for i in idx)


def main():
    data, sources = {}, {}
    for key in EMPIRES:
        path, src = fetch(key)
        if path is None:
            print("no flag for", key)
            continue
        data["emp_" + key] = pixel(path)
        sources[key] = src
        print(key, "<-", src)
        time.sleep(0.3)
    head = (
        "--!strict\n-- Generated by tools/build_empire_flags.py (historical flags from Wikimedia Commons, public\n"
        "-- domain), 30 x 20 pixels like the country flags. Do not edit.\n"
    )
    out = os.path.join("src", "shared", "Data", "FlagData", "Empires.luau")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(head + "return {\n" + "".join(f'\t["{c}"] = "{d}",\n' for c, d in sorted(data.items())) + "}\n")
    sheet = Image.new("RGB", (5 * (FW + 2), (len(data) // 5 + 1) * (FH + 2)), (40, 40, 40))
    for k, (c, d) in enumerate(sorted(data.items())):
        hx, ix = d.split("|")
        pal = [tuple(int(hx[i:i + 2], 16) for i in (j, j + 2, j + 4)) for j in range(0, len(hx), 6)]
        im = Image.new("RGB", (FW, FH))
        im.putdata([pal[IDX.index(ch)] for ch in ix])
        sheet.paste(im, ((k % 5) * (FW + 2), (k // 5) * (FH + 2)))
    sheet.resize((sheet.width * 6, sheet.height * 6), Image.NEAREST).save(
        os.path.join("tools", "assets_out", "empire_flags_preview.png")
    )
    print(len(data), "empire flags ->", out)


if __name__ == "__main__":
    main()
